#!/usr/bin/env python3
"""Write the diagnostics bundle's variant kernels from vLLM 26382f5cf's sources.

usage: make_diagnostics.py VLLM_REPO

Each variant is the 26382f5cf kernel's source with one part replaced, written as a plain
module (TileLang parses a kernel from its source file), so a variant differs from the
kernel it is timed against only where its name says:

- mhc_variants.py, ``project_streams`` (mHC's entry projection) by how each stream's fn
  tile reaches shared memory: A as at 26382f5cf (T.Parallel load and split); B loaded
  into registers ahead and split with scalar stores (vLLM 8e596b329, reverted); C loaded
  ahead and split with 4-wide vector stores; D the scalar split without loading ahead;
  E loaded ahead into a fragment and split with T.Parallel.
- metadata_variants.py, ``decode_metadata_kernel``'s page part: old (every column, as at
  26382f5cf); dyn (the live pages as the loop bound, vLLM 3cd92e872); static_var (the
  table width's trip count, the live pages in a T.alloc_var, 1072d662b); static_expr
  (the same with the live pages as an expression); select (the old loop and select, the
  store under the live pages).
"""
import re
import subprocess
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent / "bundles" / "audit-diagnostics"
HEADER = '''# Generated by experiments/2026-10-25-kernel-audit/make_diagnostics.py from vLLM 26382f5cf.
# ruff: noqa
import tilelang
import tilelang.language as T

'''


def source(repo: str, path: str) -> str:
    return subprocess.run(["git", "-C", repo, "show", f"26382f5cf:{path}"], check=True,
                          capture_output=True, text=True).stdout


def function(text: str, name: str, end: str) -> str:
    start = text.index(f"@tilelang.jit(pass_configs=", text.index(f"def {name}(") - 60)
    stop = text.index(end, start) + len(end)
    return text[start:stop]


MHC_MACROS = '''
    FV = MIXES * block_H // threads

    @T.macro
    def load_fn(Fn, k0, fv, tx):
        for k in T.unroll(FV // 4):
            e = (k * threads + tx) * 4
            for v in T.vectorized(4):
                fv[k * 4 + v] = Fn[e // block_H, k0 + e % block_H + v]

    @T.macro
    def split_regs(fv, tx, F_shared, F_mid, F_low):
        for k in T.unroll(FV // 4):
            e = (k * threads + tx) * 4
            for v in T.{STORE}(4):
                f = fv[k * 4 + v]
                high = T.reinterpret(T.reinterpret(f, T.uint32) & 0xFFFFE000, T.float32)
                rest = f - high
                middle = T.reinterpret(
                    T.reinterpret(rest, T.uint32) & 0xFFFFE000, T.float32
                )
                F_shared[e // block_H, e % block_H + v] = high
                F_mid[e // block_H, e % block_H + v] = middle
                F_low[e // block_H, e % block_H + v] = rest - middle

    @T.macro
    def load_frag(Fn, k0, F_regs):
        for i, j in T.Parallel(MIXES, block_H):
            F_regs[i, j] = Fn[i, k0 + j]

    @T.macro
    def split_frag(F_regs, F_shared, F_mid, F_low):
        for i, j in T.Parallel(MIXES, block_H):
            f = F_regs[i, j]
            high = T.reinterpret(T.reinterpret(f, T.uint32) & 0xFFFFE000, T.float32)
            rest = f - high
            middle = T.reinterpret(
                T.reinterpret(rest, T.uint32) & 0xFFFFE000, T.float32
            )
            F_shared[i, j] = high
            F_mid[i, j] = middle
            F_low[i, j] = rest - middle
'''

# variant: (prologue load, split of the current tile, load of the next tile after the sync)
MHC = {
    "A": (None, "load_split_tf32(Fn, {k0}, F_shared, F_mid, F_low)", None),
    "B": ("load_fn(Fn, h0, fv, tx)", "split_regs(fv, tx, F_shared, F_mid, F_low)",
          "load_fn(Fn, (n + 1) * H + h0, fv, tx)"),
    "C": ("load_fn(Fn, h0, fv, tx)", "split_regs(fv, tx, F_shared, F_mid, F_low)",
          "load_fn(Fn, (n + 1) * H + h0, fv, tx)"),
    "D": (None, "load_fn(Fn, {k0}, fv, tx)\n{ind}split_regs(fv, tx, F_shared, F_mid, F_low)",
          None),
    "E": ("load_frag(Fn, h0, F_regs)", "split_frag(F_regs, F_shared, F_mid, F_low)",
          "load_frag(Fn, (n + 1) * H + h0, F_regs)"),
}


def mhc_variants(repo: str) -> str:
    text = source(repo, "vllm/models/deepseek_v4_1/tilelang/mhc.py")
    base = function(text, "project_streams", "    return mhc_project_streams\n")
    out = [HEADER, "from vllm.models.deepseek_v4_1.tilelang.mhc import (\n"
           "    _PASS_CONFIGS, BLOCK_H, MIXES, MULT,\n)\n\n"]
    for name, (prologue, split, ahead) in MHC.items():
        code = base.replace("def project_streams(", f"def project_streams_{name}(", 1)
        store = "vectorized" if name == "C" else "unroll"
        code = code.replace("    @T.prim_func\n", MHC_MACROS.replace("{STORE}", store)
                            + "\n    @T.prim_func\n", 1)
        alloc = "            red = T.alloc_local((1,), T.float32)\n"
        extra = "            fv = T.alloc_local((FV,), T.float32)\n"
        if name == "E":
            extra = "            F_regs = T.alloc_fragment((MIXES, block_H), T.float32)\n"
        code = code.replace(alloc, alloc + (extra if name != "A" else ""), 1)
        if prologue:
            anchor = "            T.clear(C_local)\n"
            code = code.replace(anchor, f"            {prologue}\n" + anchor, 1)
        # The broadcast entry's one stream, then each stream of the others.
        b_old = "                load_split_tf32(Fn, h0, F_shared, F_mid, F_low)\n"
        b_new = "                " + split.format(k0="h0", ind="                ") + "\n"
        assert code.count(b_old) == 1
        code = code.replace(b_old, b_new)
        s_old = ("                    load_split_tf32(Fn, n * H + h0, F_shared, F_mid, F_low)\n"
                 "                    T.sync_threads()\n")
        s_new = ("                    " + split.format(k0="n * H + h0", ind="                    ")
                 + "\n                    T.sync_threads()\n")
        if ahead:
            s_new += f"                    if n + 1 < MULT:\n                        {ahead}\n"
        assert code.count(s_old) == 1
        code = code.replace(s_old, s_new)
        out.append(code + "\n\n")
    return "".join(out)


PAGE_OLD = '''                req = main_reqs[offset + row]
                for k in T.serial(main_per_thread):
                    col = k * threads + tx
                    if col < main_width:
                        page_id = T.if_then_else(
                            (req >= 0) & (col < main_read_width),
                            main_table[req, col],
                            -1,
                        )
                        main_pages[row, col] = T.if_then_else(page_id > 0, page_id, -1)
'''
LIVE = ("T.min((T.max(visible[offset + row], 0) + main_page - 1) // main_page, "
        "T.min(main_read_width, main_width))")
PAGES = {
    "old": PAGE_OLD,
    "dyn": f'''                req = main_reqs[offset + row]
                live = {LIVE}
                if req < 0:
                    live = 0
                for k in T.serial(T.ceildiv(live, threads)):
                    col = k * threads + tx
                    if col < live:
                        page_id = main_table[req, col]
                        main_pages[row, col] = T.if_then_else(page_id > 0, page_id, -1)
''',
    "static_var": f'''                req = main_reqs[offset + row]
                live = {LIVE}
                if req < 0:
                    live = 0
                for k in T.serial(main_per_thread):
                    col = k * threads + tx
                    if col < live:
                        page_id = main_table[req, col]
                        main_pages[row, col] = T.if_then_else(page_id > 0, page_id, -1)
''',
    "static_expr": f'''                req = main_reqs[offset + row]
                for k in T.serial(main_per_thread):
                    col = k * threads + tx
                    if (req >= 0) & (col < {LIVE}):
                        page_id = main_table[req, col]
                        main_pages[row, col] = T.if_then_else(page_id > 0, page_id, -1)
''',
    "select": f'''                req = main_reqs[offset + row]
                for k in T.serial(main_per_thread):
                    col = k * threads + tx
                    if col < main_width:
                        page_id = T.if_then_else(
                            (req >= 0) & (col < main_read_width),
                            main_table[req, col],
                            -1,
                        )
                        if col < {LIVE}:
                            main_pages[row, col] = T.if_then_else(page_id > 0, page_id, -1)
''',
}


def metadata_variants(repo: str) -> str:
    text = source(repo, "vllm/models/deepseek_v4_1/tilelang/metadata.py")
    base = function(text, "decode_metadata_kernel", "    return metadata_decode\n")
    out = [HEADER, "from vllm.models.deepseek_v4_1.tilelang.metadata import (\n"
           "    _PASS, _threads, _window_macro,\n)\n\n"]
    for name, page_part in PAGES.items():
        code = base.replace("def decode_metadata_kernel(", f"def decode_metadata_{name}(", 1)
        # Every variant takes the main page (old ignores it), so all launch alike.
        code = code.replace("    page: int, window: int, width: int, draft: bool, replay: bool, "
                            "main_width: int\n",
                            "    page: int, window: int, width: int, draft: bool, replay: bool, "
                            "main_width: int, main_page: int\n", 1)
        assert code.count(PAGE_OLD) == 1, name
        code = code.replace(PAGE_OLD, page_part)
        if name in ("dyn", "static_var"):
            anchor = "            info = T.alloc_local((2,), T.int64)  # window start, clamped length\n"
            assert code.count(anchor) == 1
            code = code.replace(anchor, anchor + "            live = T.alloc_var(T.int32)\n")
        out.append(code + "\n\n")
    return "".join(out)


def main() -> None:
    repo = sys.argv[1]
    (OUT / "mhc_variants.py").write_text(mhc_variants(repo))
    (OUT / "metadata_variants.py").write_text(metadata_variants(repo))
    print("wrote", ", ".join(p.name for p in sorted(OUT.glob("*_variants.py"))))


if __name__ == "__main__":
    main()
